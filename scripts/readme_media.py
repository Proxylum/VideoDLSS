#!/usr/bin/env python3
"""GIFs and stills for the README: the whole pipeline on short 480p clips with an open licence (docs/media/README.md).

    python scripts/readme_media.py                 # everything: fetch sources, cut, process, render, encode GIFs
    python scripts/readme_media.py --only willie   # one clip
    python scripts/readme_media.py --stage gif     # re-encode the GIFs from the frames already on disk
    python scripts/readme_media.py --media-dir docs/media --out <work dir>

Per clip: <work>/<clip>/in_480p.mp4 (the 480p input), after.mp4 (dlssvid process: depth -> flow -> DLSS SR x2 -> NR -> FG x2),
after_passes/, frame dumps, and the GIF/PNG files copied into --media-dir (docs/media/ by default). Needs the dlssvid CLI
(build/release/bin or DLSSVID_CLI), ffmpeg/ffprobe on PATH, Pillow + numpy (the models/export venv has them) and an
NVIDIA RTX GPU with the DLSS DLLs in bin/nvidia (README: NVIDIA runtimes). The work dir defaults to the workspace's
Output/results/readme-media when the project lives in <workspace>/Project/, else build/release/readme-media.
"""
